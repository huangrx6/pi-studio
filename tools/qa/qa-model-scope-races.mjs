import { composerValue } from './fixtures/composer-editor.mjs';
/** App callback scope races against the production renderer, no provider calls. */
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright-core';
import { serveProductionRenderer } from './fixtures/production-renderer-server.mjs';
import { installConversationFixture } from './fixtures/conversation-refinement.mjs';
import { installModelScopeFixture } from './fixtures/model-scope.mjs';
const root = fileURLToPath(new URL('../..', import.meta.url));
const output = path.join(root, '.qa', 'model-scope-races');
await mkdir(output, { recursive: true });
const server = await serveProductionRenderer(root);
const result = { pageErrors: [], checks: [] };
let browser; let page;
try {
  browser = await chromium.launch({ executablePath: process.env.CHROME_BIN || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
  page = await browser.newPage({ viewport: { width: 1100, height: 760 } });
  page.setDefaultTimeout(15_000);
  page.on('pageerror', (error) => result.pageErrors.push(error.message));
  await page.route('**/*', (route) => route.request().url().startsWith(server.origin) || /^(data|blob):/.test(route.request().url()) ? route.continue() : route.abort());
  await page.addInitScript({ content: `(${installConversationFixture.toString()})(); (${installModelScopeFixture.toString()})();` });
  const composer = page.getByRole('textbox', { name: '发送给 Pi 的消息', exact: true });
  const label = page.locator('.model-label');
  const flush = async () => page.evaluate(() => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  const begin = async () => {
    await page.goto(server.origin);
    await page.locator('.workspace-row').first().waitFor();
    for (const row of await page.locator('.workspace-row').all()) if (await row.getAttribute('aria-expanded') !== 'true') await row.click();
  };
  const open = async (name) => { await page.locator('.session-row').filter({ has: page.locator('.session-title').filter({ hasText: new RegExp(`^${name}$`) }) }).click(); await page.locator('.chat-heading h1').filter({ hasText: new RegExp(`^${name}$`) }).waitFor(); };
  const chooseNewModel = async () => { await label.click(); await page.locator('.model-menu-row').first().click(); await page.getByRole('menuitemradio', { name: 'New Model', exact: true }).click(); };

  await begin();
  await open('Race A');
  await page.evaluate(() => { window.__modelScopeQa.holdConfigure = true; });
  await label.click();
  await page.getByRole('menuitem').filter({ hasText: '切换会话模型' }).click();
  await page.getByRole('menuitemradio', { name: 'New Model', exact: true }).click();
  await page.waitForFunction(() => window.__modelScopeQa.pending('configure') === 1);
  await open('Race B');
  await composer.fill('B 会话的草稿');
  assert.match(await label.innerText(), /Session B/);
  await page.evaluate(() => window.__modelScopeQa.release('configure'));
  await flush();
  assert.match(await label.innerText(), /Session B/, 'A configuration response does not overwrite B in the same workspace');
  assert.equal(await composerValue(composer), 'B 会话的草稿');
  result.checks.push('held conversationConfigure A → B in same workspace preserves B selection/draft');

  await begin();
  await open('Race A');
  await page.evaluate(() => { window.__modelScopeQa.holdCatalogFor = '/qa/workspace-a'; });
  await label.click();
  await page.waitForFunction(() => window.__modelScopeQa.pending('catalog') > 0);
  await open('Race C');
  await composer.fill('C 会话的草稿');
  await page.evaluate(() => window.__modelScopeQa.release('catalog'));
  await flush();
  assert.match(await label.innerText(), /Session C/);
  assert.equal(await composerValue(composer), 'C 会话的草稿');
  await page.locator('.new-chat').click();
  await page.waitForFunction(() => document.querySelector('.model-label')?.textContent.includes('Default B'));
  result.checks.push('held workspace A catalog cannot overwrite workspace B session or new-chat default');

  await begin();
  await open('Race C');
  await page.locator('.new-chat').click();
  await page.waitForFunction(() => document.querySelector('.model-label')?.textContent.includes('Default B'));
  await page.evaluate(() => { window.__modelScopeQa.holdCatalogFor = '/qa/workspace-a'; });
  await page.locator('.workspace-row').filter({ hasText: 'Workspace A' }).hover();
  await page.getByRole('button', { name: '在Workspace A中新建对话', exact: true }).click();
  await page.waitForFunction(() => window.__modelScopeQa.pending('catalog') > 0);
  await page.locator('.workspace-row').filter({ hasText: 'Workspace B' }).hover();
  await page.getByRole('button', { name: '在Workspace B中新建对话', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.model-label')?.textContent.includes('Default B'));
  await composer.fill('B 工作区新会话草稿');
  await page.evaluate(() => window.__modelScopeQa.release('catalog'));
  await flush();
  assert.match(await label.innerText(), /Default B/);
  assert.equal(await composerValue(composer), 'B 工作区新会话草稿');
  result.checks.push('held workspace A draft defaults cannot overwrite workspace B draft selection/text');

  await begin();
  await open('Race A');
  await page.locator('.new-chat').click();
  await page.waitForFunction(() => document.querySelector('.model-label')?.textContent.includes('Default A'));
  await page.evaluate(() => { window.__modelScopeQa.holdDefaultsFor = '/qa/workspace-a'; });
  await chooseNewModel();
  await page.waitForFunction(() => window.__modelScopeQa.pending('defaults') === 1);
  await page.locator('.workspace-row').filter({ hasText: 'Workspace B' }).hover();
  await page.getByRole('button', { name: '在Workspace B中新建对话', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.model-label')?.textContent.includes('Default B'));
  await composer.fill('B 默认模型写入期间的草稿');
  await page.evaluate(() => window.__modelScopeQa.release('defaults'));
  await flush();
  assert.match(await label.innerText(), /Default B/);
  assert.equal(await composerValue(composer), 'B 默认模型写入期间的草稿');
  result.checks.push('held setDefaultModel write for workspace A does not block B defaults load or overwrite its draft');

  await begin();
  await page.evaluate(() => { window.__modelScopeQa.holdSubscriptionFor = 'a'; });
  await open('Race A');
  await page.waitForFunction(() => window.__modelScopeQa.pending('subscription') === 1);
  await chooseNewModel();
  await page.waitForFunction(() => document.querySelector('.model-label')?.textContent.includes('New Model'));
  await composer.fill('订阅快照迟到时保留草稿');
  await page.evaluate(() => window.__modelScopeQa.release('subscription'));
  await flush();
  assert.match(await label.innerText(), /New Model/);
  assert.equal(await composerValue(composer), '订阅快照迟到时保留草稿');
  result.checks.push('stale subscribeConversation model cannot overwrite a newer saved selection');

  await begin();
  await open('Race A');
  await flush();
  await page.evaluate(() => { window.__modelScopeQa.holdCompletionFor = 'a'; window.__modelScopeQa.emit('a', 'run.completed', { inputs: [], running: false }); });
  await page.waitForFunction(() => window.__modelScopeQa.pending('completion') === 1);
  await chooseNewModel();
  await page.waitForFunction(() => document.querySelector('.model-label')?.textContent.includes('New Model'));
  await page.evaluate(() => window.__modelScopeQa.release('completion'));
  await flush();
  assert.match(await label.innerText(), /New Model/);
  result.checks.push('stale run.completed snapshot cannot overwrite a newer saved selection');

  await begin();
  await open('Race A');
  await composer.fill('A 的历史读取竞态草稿');
  await page.evaluate(() => { window.__modelScopeQa.holdConfigure = true; });
  await chooseNewModel();
  await page.waitForFunction(() => window.__modelScopeQa.pending('configure') === 1);
  await open('Race B');
  await page.evaluate(() => { window.__modelScopeQa.holdPageFor = 'a'; });
  await page.locator('.session-row').filter({ has: page.locator('.session-title', { hasText: /^Race A$/ }) }).click();
  await page.waitForFunction(() => window.__modelScopeQa.pending('page') > 0);
  await page.evaluate(() => window.__modelScopeQa.release('configure'));
  await flush();
  await page.evaluate(() => { window.__modelScopeQa.holdPageFor = ''; window.__modelScopeQa.release('page'); });
  await page.locator('.chat-heading h1').filter({ hasText: /^Race A$/ }).waitFor();
  assert.match(await label.innerText(), /New Model/);
  assert.equal(await composerValue(composer), 'A 的历史读取竞态草稿');
  await open('Race B');
  await open('Race A');
  assert.match(await label.innerText(), /New Model/, 'revisiting the cached transcript does not restore the stale page model');
  result.checks.push('older conversationPage response and cached revisits preserve a completed model write');
  assert.deepEqual(result.pageErrors, []);
  console.log(`Model scope race QA passed: ${result.checks.length} production App callback scenarios.`);
} catch (error) {
  if (page) await page.screenshot({ path: path.join(output, 'failure.png') }).catch(() => {});
  throw error;
} finally {
  await writeFile(path.join(output, 'results.json'), JSON.stringify(result, null, 2));
  if (browser) await browser.close();
  await server.close();
}
