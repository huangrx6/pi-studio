import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright-core';
import { installPerformanceFixture } from './fixtures/performance.mjs';
import { installSessionViewsFixture } from './fixtures/session-views.mjs';
import { serveProductionRenderer } from './fixtures/production-renderer-server.mjs';

const root = new URL('../../', import.meta.url);
const output = new URL('.qa/session-views/', root);
await mkdir(output, { recursive: true });
const server = await serveProductionRenderer(fileURLToPath(root));
let browser;
try {
  browser = await chromium.launch({ executablePath: process.env.CHROME_BIN || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' });
  const page = await browser.newPage({ viewport: { width: 1440, height: 920 } });
  page.setDefaultTimeout(6500);
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route('**/*', route => route.request().url().startsWith(server.origin) ? route.continue() : route.abort());
  await page.addInitScript({ content: `(${installPerformanceFixture})({sessionCount:1,turnCount:2});(${installSessionViewsFixture})();` });
  await page.goto(server.origin);
  await page.locator('.session-row').first().click();
  await page.locator('.assistant-response').first().waitFor();

  const button = name => page.getByRole('button', { name, exact: true });
  async function openView(name) {
    await button('打开工作区面板').click();
    await page.getByRole('group', { name: '会话视图' }).getByRole('button', { name: new RegExp(`^${name}`) }).click();
  }
  async function returnToChat() {
    assert.equal(await page.locator('.session-view-head').getByRole('button', { name: '返回对话' }).count(), 0);
    await openView('返回对话');
    await page.locator('.assistant-response').first().waitFor();
  }
  async function capture(name) {
    await page.mouse.move(12, 12);
    await page.screenshot({ path: fileURLToPath(new URL(`${name}.png`, output)), animations: 'disabled' });
  }
  await openView('子智能体');
  const tasks = page.locator('.agent-list-row');
  const agentSearch = page.getByRole('textbox', { name: '搜索子智能体' });
  await tasks.first().waitFor();
  assert.equal(await tasks.count(), 4);
  assert.match(await tasks.nth(1).innerText(), /找不到 fixtures/);
  assert.match(await page.locator('.agent-usage').innerText(), /7.8k.*25k/);
  await capture('subagents-dark');
  await agentSearch.fill('session.json');
  assert.equal(await tasks.count(), 1);
  await agentSearch.fill('没有这个任务');
  await button('清除筛选').click();
  await page.getByRole('button', { name: /^需处理/ }).click();
  assert.equal(await tasks.count(), 2);
  await page.getByRole('button', { name: /^回复.*2/ }).click();
  const form = page.locator('.agent-supervisor-reply');
  await form.locator('textarea').fill('导出为 CSV');
  await form.getByRole('button', { name: '选择待回复的问题' }).click();
  await page.getByRole('option', { name: /是否保留英文列名/ }).click();
  await form.locator('textarea').fill('保留英文列名');
  await form.getByRole('button', { name: '选择待回复的问题' }).click();
  await page.getByRole('option', { name: /导出文件使用哪种格式/ }).click();
  assert.equal(await form.locator('textarea').inputValue(), '导出为 CSV');
  await page.evaluate(() => { window.sessionViewsQa.failReply = true; });
  await button('发送回复').click();
  await form.getByRole('alert').waitFor();
  assert.equal(await form.locator('textarea').inputValue(), '导出为 CSV');
  await page.evaluate(() => { window.sessionViewsQa.failReply = false; });
  await form.locator('textarea').press('Control+Enter');
  await form.waitFor({ state: 'detached' });
  assert.deepEqual(await page.evaluate(() => window.sessionViewsQa.replies.map(({ requestId, message }) => ({ requestId, message }))), [{ requestId: 'format', message: '导出为 CSV' }]);
  await button('回复').click();
  assert.equal(await form.locator('textarea').inputValue(), '保留英文列名');
  await button('收起').click();
  await page.evaluate(() => { window.sessionViewsQa.failList = true; });
  await button('刷新子智能体').click();
  await page.getByText('未能刷新任务列表').waitFor();
  assert.equal(await tasks.count(), 2);
  await page.evaluate(() => { window.sessionViewsQa.failList = false; });
  await page.locator('.agent-context-alert').getByRole('button', { name: '重试' }).click();
  await page.locator('.agent-context-alert').waitFor({ state: 'detached' });
  await page.getByRole('button', { name: /^全部任务/ }).click();
  await button('流程图视图').click();
  await page.getByRole('button', { name: /布局审查.*查看记录/ }).waitFor();
  await page.evaluate(() => { window.sessionViewsQa.failTranscript = true; });
  await page.getByRole('button', { name: /布局审查.*查看记录/ }).press('Enter');
  await page.getByRole('button', { name: '重新读取' }).waitFor();
  await page.evaluate(() => { window.sessionViewsQa.failTranscript = false; });
  await button('重新读取').click();
  await page.locator('.agent-transcript.messages').waitFor();
  await button('展开完整指令').click();
  await button('收起指令').waitFor();
  await button('返回列表').click();
  await button('列表视图').click();
  await returnToChat();

  await openView('轨迹');
  const rows = page.locator('.conversation-trace-item');
  const cells = page.locator('.trace-activity-cell');
  const detail = page.getByRole('complementary', { name: '轨迹详情' });
  await rows.first().waitFor();
  assert.ok(await cells.count() > await rows.count(), 'long history starts with a bounded list');
  await cells.first().focus();
  await cells.first().press('End');
  await cells.last().press('Enter');
  await detail.waitFor();
  await page.waitForFunction(() => document.querySelector('.conversation-trace-list').scrollTop > 400);
  await button('关闭轨迹详情').press('Escape');
  await page.waitForFunction(() => document.activeElement?.classList.contains('is-selected') || document.activeElement?.classList.contains('conversation-trace-item'));
  await page.getByRole('button', { name: /^异常.*1/ }).click();
  assert.equal(await rows.count(), 1);
  await rows.first().click();
  await detail.getByRole('tab', { name: '结果', exact: true }).click();
  assert.match(await detail.getByRole('tabpanel').innerText(), /路径不存在/);
  await detail.getByRole('button', { name: '复制结果' }).click();
  assert.equal(await page.evaluate(() => window.sessionViewsQa.copied), '路径不存在，请检查模块入口。');
  await capture('trace-error-dark');
  assert.equal(await page.evaluate(() => window.sessionViewsQa.reads), 0, 'tool result is already in the transcript');
  await button('关闭轨迹详情').click();
  await page.getByRole('button', { name: /^全部/ }).click();
  const traceSearch = page.getByRole('textbox', { name: '搜索轨迹' });
  await traceSearch.fill('没有这个轨迹');
  await button('清除筛选').click();
  await traceSearch.fill('request-0');
  await rows.filter({ hasText: '模型调用' }).first().click();
  await page.evaluate(() => { window.sessionViewsQa.failSnapshot = true; });
  await detail.getByRole('tab', { name: '系统提示词' }).click();
  await button('重新读取快照').waitFor();
  await page.evaluate(() => { window.sessionViewsQa.failSnapshot = false; });
  await button('重新读取快照').click();
  await detail.locator('pre').filter({ hasText: '按文件证据核对结论。' }).waitFor();
  await detail.getByRole('tab', { name: '系统提示词' }).press('ArrowRight');
  await detail.getByText('核对模块文件。', { exact: true }).last().waitFor();
  assert.equal(await page.evaluate(() => window.sessionViewsQa.reads), 2);
  await button('关闭轨迹详情').click();
  await button('清空轨迹搜索').click();
  await rows.filter({ hasText: 'src/modules/0.ts' }).first().click();
  await capture('trace-dark');
  await page.setViewportSize({ width: 1176, height: 740 });
  await button('打开右侧面板').click();
  await page.waitForFunction(() => getComputedStyle(document.querySelector('.conversation-trace-list')).visibility === 'hidden');
  assert.equal(await detail.isVisible(), true);
  assert.ok(await detail.evaluate(node => node.scrollWidth <= node.clientWidth + 1));
  await button('下一条').click();
  assert.match(await detail.locator('.conversation-trace-detail-head').innerText(), /助手/);
  assert.equal(await button('下一条').evaluate(el => el === document.activeElement), true);
  await button('上一条').click();
  assert.match(await detail.locator('.conversation-trace-detail-head').innerText(), /read/);
  await capture('trace-narrow');
  await button('关闭轨迹详情').click();
  assert.equal(await rows.first().isVisible(), true);
  await page.setViewportSize({ width: 1440, height: 920 });
  await button('收起右侧面板').click();
  await returnToChat();

  await openView('扩展');
  const groups = page.locator('.extension-hub-card');
  await groups.first().waitFor();
  const manage = button('管理扩展');
  const [control, icon, label] = await Promise.all([manage, manage.locator('svg'), manage.locator('span')].map(part => part.boundingBox()));
  const centerY = rect => rect.y + rect.height / 2;
  assert.ok(Math.abs(centerY(icon) - centerY(control)) <= 1 && Math.abs(centerY(label) - centerY(control)) <= 1);
  assert.ok(Math.abs((icon.x - control.x) - (control.x + control.width - label.x - label.width)) <= 1);
  assert.ok(label.x - icon.x - icon.width >= 8);
  await capture('extensions-dark');
  assert.equal(await groups.count(), 2);
  assert.equal(await groups.first().locator('.extension-hub-panel').count(), 2);
  await button('打开 会话用量 详情').click();
  await page.locator('.extension-page').waitFor();
  await button('扩展中心').click();
  await button('下移 运行监测').click();
  await page.waitForFunction(() => window.sessionViewsQa.order.globalOrder[0] === 'workspace');
  await button('当前会话').click();
  await button('上移 运行监测').click();
  await page.waitForFunction(() => window.sessionViewsQa.order.sessionOrders['perf-0']?.[0] === 'monitor');
  await button('恢复全局').click();
  await page.waitForFunction(() => !window.sessionViewsQa.order.sessionOrders['perf-0']);
  await page.evaluate(() => { window.sessionViewsQa.holdNextWrite = true; });
  await button('紧凑列表').click();
  assert.match(await page.locator('.extension-hub-items').getAttribute('class'), /is-list/);
  await button('卡片布局').click();
  await page.evaluate(async () => {
    window.sessionViewsQa.releaseWrite();
    await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)));
  });
  assert.match(await page.locator('.extension-hub-items').getAttribute('class'), /is-grid/, 'a late acknowledgement cannot restore an old layout');
  await page.evaluate(() => { document.documentElement.dataset.theme = 'light'; });
  await capture('extensions-light');
  await page.setViewportSize({ width: 1176, height: 740 });
  await button('打开右侧面板').click();
  assert.ok(await groups.first().evaluate(node => node.scrollWidth <= node.clientWidth + 1));
  await returnToChat();
  await openView('子智能体');
  await page.locator('.agent-list-row').first().waitFor();
  assert.ok(await page.locator('.agent-overview').evaluate(node => node.scrollWidth <= node.clientWidth + 1));
  await capture('subagents-narrow');
  await page.goto(`${server.origin}/?empty`);
  await page.locator('.session-row').first().click();
  await openView('子智能体');
  await page.getByText('这次对话还没有子智能体').waitFor();
  await openView('轨迹');
  await page.getByText('还没有执行记录').waitFor();
  await openView('扩展');
  await page.getByText('暂无会话扩展').waitFor();
  await button('管理扩展').click();
  await page.locator('.settings-overlay [data-settings-page="extensions"][aria-current="page"]').waitFor();
  await page.getByText('还没有安装扩展', { exact: true }).waitFor();
  assert.deepEqual(errors, []);
  console.log('Passed session navigation, task filters and retries, per-question drafts, keyboard graph and transcript, long trace jumps, deferred snapshots, extension grouping and ordering, light/dark and split layouts.');
} finally {
  await browser?.close();
  await server.close();
}
