import type { ClipboardEvent } from 'react';

function isWholeSelection(root: HTMLDivElement, selection: Selection): boolean {
  if (!selection.rangeCount || selection.isCollapsed) return false;
  if (!root.contains(selection.anchorNode) || !root.contains(selection.focusNode)) return false;

  const selectedRange = selection.getRangeAt(0);
  const contentRange = root.ownerDocument.createRange();
  contentRange.selectNodeContents(root);

  // A full message selection can omit generated list markers such as `1.` and
  // `2.` because those markers come from CSS. Compare the range boundaries
  // rather than the browser-produced selection text.
  return selectedRange.compareBoundaryPoints(0, contentRange) === 0
    && selectedRange.compareBoundaryPoints(2, contentRange) === 0;
}

function normalizeForMatch(value: string): string {
  return value
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
    .replace(/[`*_~]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

function selectedListSource(root: HTMLDivElement, selection: Selection, source: string): string | undefined {
  if (!selection.rangeCount || !selection.anchorNode || !selection.focusNode) return undefined;
  const range = selection.getRangeAt(0);
  const anchorList = selection.anchorNode.parentElement?.closest('ol, ul');
  const focusList = selection.focusNode.parentElement?.closest('ol, ul');
  if (!anchorList || anchorList !== focusList || !root.contains(anchorList)) return undefined;

  const items = Array.from(anchorList.children)
    .filter((node): node is HTMLLIElement => node instanceof HTMLLIElement)
    .filter((item) => {
      try {
        return range.intersectsNode(item);
      } catch {
        return false;
      }
    });
  if (items.length === 0) return undefined;

  const targets = items.map((item) => normalizeForMatch(item.textContent || ''));
  if (targets.some((target) => !target)) return undefined;
  const selectedText = normalizeForMatch(selection.toString());
  const expectedText = normalizeForMatch(targets.join(' '));
  if (items.length === 1 && selectedText !== expectedText) return undefined;

  const sourceLines = sourceLinesForList(source, anchorList, targets);
  if (sourceLines) return sourceLines.join('\n');

  const ordered = anchorList.tagName.toLowerCase() === 'ol';
  const firstIndex = Array.from(anchorList.children).indexOf(items[0]);
  const start = ordered ? Number(anchorList.getAttribute('start') || 1) + firstIndex : 0;
  return items.map((item, index) => {
    const marker = ordered ? `${start + index}. ` : '- ';
    return `${marker}${item.textContent?.trim() || ''}`;
  }).join('\n');
}

// The rendered list marker is generated by the browser and is not part of
// `selection.toString()`. Recover the original source lines when the selected
// items can be matched to one contiguous Markdown list in the source.
function sourceLinesForList(source: string, list: Element, targets: string[]): string[] | undefined {
  const ordered = list.tagName.toLowerCase() === 'ol';
  const marker = ordered ? /^\s*\d+[.)]\s+(.+)$/ : /^\s*[-*+]\s+(.+)$/;
  const candidates = source.split(/\r?\n/)
    .map((line) => ({ line, text: line.match(marker)?.[1] }))
    .filter((entry): entry is { line: string; text: string } => Boolean(entry.text));
  for (let index = 0; index <= candidates.length - targets.length; index += 1) {
    const match = targets.every((target, offset) => normalizeForMatch(candidates[index + offset].text) === target);
    if (match) return candidates.slice(index, index + targets.length).map((entry) => entry.line);
  }
  return undefined;
}

export function copyMarkdownSource(event: ClipboardEvent<HTMLDivElement>, source: string) {
  const selection = event.currentTarget.ownerDocument.getSelection();
  if (!selection) return;

  const listSource = selectedListSource(event.currentTarget, selection, source);
  if (listSource) {
    event.preventDefault();
    event.clipboardData.setData('text/plain', listSource);
    return;
  }
  if (!isWholeSelection(event.currentTarget, selection)) return;

  event.preventDefault();
  event.clipboardData.setData('text/plain', source);
}
