const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const test = require('node:test');
const { createStudioDatabase } = require('../../electron/core/studio-db.cjs');
const { archiveNextEntry, prepareAssetArchive } = require('../../electron/services/conversation-asset-archive.cjs');
const { assetOwner, bindConversationUploads, removeConversationAssets } = require('../../electron/services/conversation-assets.cjs');

test('a restarted Studio archives exact parent and nested-agent inputs and delivered outputs in their owning session', async t => {
  const root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'studio-owned-attachments-')));
  const workspace = path.join(root, '.project-container', 'workspace');
  fs.mkdirSync(workspace, { recursive: true });
  const filename = path.join(root, 'studio.sqlite');
  let studio = createStudioDatabase(filename);
  const { openNodeSqliteStorage } = await import('@earendil-works/pi-durable/storage/sqlite/node');
  const { BACKGROUND_CONTEXT } = await import('@earendil-works/chord/context');
  const durable = await openNodeSqliteStorage(filename, { prefix: 'durable_' });
  t.after(async () => { await durable.close(BACKGROUND_CONTEXT); studio.close(); fs.rmSync(root, { recursive: true, force: true }); });
  const parent = studio.insertConversation({ id: '11', workspace, kind: 'conversation', title: 'Parent' });
  const neighbor = studio.insertConversation({ id: '22', workspace, kind: 'conversation', title: 'Neighbor' });
  for (const [id, owner] of [[11,null],[12,11],[13,12],[22,null]]) {
    studio.db.prepare("INSERT INTO durable_conversations(id,owner_conversation_id,record) VALUES(?,?,'{}')").run(id, owner);
  }
  const output = path.join(workspace, '销售表.xlsx');
  fs.writeFileSync(output, 'delivered workbook');
  const image = { type: 'image', mimeType: 'image/png', data: Buffer.from('png bytes').toString('base64') };
  const entry = (id, owner, role, content, data = {}, other = {}) => {
    const record = { id, kind: role === 'user' ? 'studio.user' : 'pi.' + role, data, model: [{ role, content, ...other }] };
    studio.db.prepare('INSERT INTO durable_entries(id,conversation_id,commit_seq,record) VALUES(?,?,?,?)').run(id, owner, id, JSON.stringify(record));
  };
  const draft = path.join(root, 'attachments', 'draft');
  fs.mkdirSync(draft, { recursive: true });
  const original = path.join(draft, '7a4ee083-316f-47eb-ac83-31e88b027c13-资料.pdf');
  fs.writeFileSync(original, 'original upload');
  entry(501, 11, 'user', [image], { attachments: [original], imageNames: ['截图.png'] });
  entry(502, 13, 'assistant', [{ type: 'text', text: '[旧文件](销售表.xlsx)' }]);
  entry(503, 13, 'assistant', [{ type: 'toolCall', id: 'write-1', name: 'write', arguments: { path: '旧版.txt', content: 'at the time of writing' } }]);
  entry(504, 13, 'toolResult', [], {}, { toolName: 'write', toolCallId: 'write-1', isError: false });
  prepareAssetArchive(studio);
  entry(505, 13, 'toolResult', [image], {}, { toolName: 'render' });
  entry(506, 13, 'assistant', [{ type: 'text', text: '[报表](销售表.xlsx) [外部引用](../../private.file) [敏感](.env)' }]);
  entry(507, 22, 'user', [image]);
  assert.ok(studio.attachmentSessionIds().includes('13'));
  const owner = assetOwner(studio.db, 13);
  assert.equal(owner.publicId, parent.publicId);
  assert.equal(owner.childId, '13');
  await archiveNextEntry(studio, root);
  studio.close();
  studio = createStudioDatabase(filename);
  prepareAssetArchive(studio);
  while (await archiveNextEntry(studio, root)) { /* drain persisted journal */ }
  const [project] = fs.readdirSync(path.join(root, 'attachments', 'projects'));
  const sessions = path.join(root, 'attachments', 'projects', project, 'sessions');
  const parentDir = path.join(sessions, parent.publicId), child = path.join(parentDir, 'agents', '13');
  const manifest = (dir, side, id) => JSON.parse(fs.readFileSync(path.join(dir, side, String(id), 'manifest.json'), 'utf8'));
  const inputs = manifest(parentDir, 'inputs', 501).files;
  assert.deepEqual(inputs.map(i => i.name), ['资料.pdf', '截图.png']);
  assert.equal(fs.readFileSync(path.join(parentDir, inputs[0].file), 'utf8'), 'original upload');
  assert.equal(fs.readFileSync(path.join(parentDir, inputs[1].file), 'utf8'), 'png bytes');
  assert.equal(manifest(child, 'outputs', 502).files[0].availability, 'historical-reference');
  assert.equal(fs.readFileSync(path.join(child, manifest(child, 'outputs', 504).files[0].file), 'utf8'), 'at the time of writing');
  assert.equal(manifest(child, 'outputs', 505).files[0].source, 'render');
  const links = manifest(child, 'outputs', 506).files;
  assert.equal(links.length, 2);
  assert.equal(links[1].availability, 'outside-workspace');
  assert.equal(links[1].file, undefined);
  fs.unlinkSync(output);
  assert.equal(fs.readFileSync(path.join(child, links[0].file), 'utf8'), 'delivered workbook');
  const bound = bindConversationUploads(parent, [original], root);
  entry(508, 13, 'user', [{ type: 'text', text: '[资料](' + bound[0] + ')' }]);
  await archiveNextEntry(studio, root);
  const delegated = manifest(child, 'inputs', 508).files[0];
  assert.equal(delegated.name, '资料.pdf');
  assert.equal(fs.readFileSync(path.join(child, delegated.file), 'utf8'), 'original upload');
  assert.deepEqual(bindConversationUploads(parent, bound, root), bound);
  assert.throws(() => bindConversationUploads(parent, [filename], root));
  assert.equal(removeConversationAssets(owner, root), true);
  assert.equal(fs.existsSync(child), false);
  assert.equal(fs.existsSync(path.join(parentDir, inputs[0].file)), true);
  assert.equal(removeConversationAssets(parent, root), true);
  assert.equal(fs.existsSync(path.join(sessions, neighbor.publicId)), true);
});
