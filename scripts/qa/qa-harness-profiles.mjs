/** Check the Harness library and dialogs against isolated Studio storage. */
import assert from 'node:assert/strict';
import { mkdir, mkdtemp, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { assertSettingsRowLinkHover, launchTestDesktop } from './fixtures/isolated-desktop.mjs';

const output = fileURLToPath(new URL('../../.qa/harness-profiles/', import.meta.url));
const base = await mkdtemp(path.join(os.tmpdir(), 'pi-studio-harness-library-'));
const workspace = path.join(base, 'workspace');
const data = path.join(base, 'profile');
await Promise.all([workspace, data, output].map(dir => mkdir(dir, { recursive: true })));
let app;
try {
  const desktop = await launchTestDesktop(workspace, data, 1240, 850);
  app = desktop.app;
  const page = desktop.page;
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.emulateMedia({ reducedMotion: 'reduce' });
  const cdp = await page.context().newCDPSession(page);
  await app.evaluate(({ dialog }, cwd) => {
    dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [cwd] });
  }, workspace);
  await page.getByRole('button', { name: '打开工作区', exact: true }).click();
  await page.locator('[data-workspace-cwd]').waitFor();
  await page.locator('.sidebar-bottom button[title="设置"]').click();
  const nav = page.locator('.settings-navigation');
  await nav.locator('[data-settings-page="harness"]').click();
  const harness = page.locator('.harness-settings');
  const cards = harness.locator('.settings-profile-card');
  const grid = harness.locator('.settings-profile-grid');
  const baseline = cards.filter({ hasText: 'studio-coding' });
  const actions = harness.locator('.settings-profile-toolbar .settings-profile-actions');
  const create = actions.getByRole('button', { name: '新建配置', exact: true });
  const policyButton = actions.getByRole('button', { name: '全局运行策略', exact: true });
  const edit = harness.getByRole('dialog', { name: '编辑 Harness 配置', exact: true });
  const policy = harness.getByRole('dialog', { name: '全局运行策略', exact: true });
  const saved = () => page.evaluate(cwd => window.piApi.harnessSettings(cwd), workspace);
  const cancel = async dialog => {
    await dialog.getByRole('button', { name: '取消', exact: true }).click();
    await dialog.waitFor({ state: 'detached' });
  };
  async function capture(name, target = page) {
    await page.locator('.settings-toast').first().waitFor({ state: 'hidden' });
    await target.screenshot({ path: path.join(output, name + '.png'), animations: 'disabled' });
  }
  const markOf = card => card.locator('.harness-profile-icon').evaluate(node => ({
    shape: node.dataset.shape,
    ink: node.dataset.ink,
    layers: [...node.querySelector('.harness-profile-layers').children].map(layer => [layer.style.width, layer.className]),
  }));
  const iconButton = dialog => dialog.getByRole('button', { name: '更换方案图标' });
  async function checkMoreMenu(dialog, captureName) {
    const trigger = dialog.getByRole('button', { name: '更多配置操作' });
    const menu = dialog.getByRole('menu', { name: '更多配置操作' });
    const scroll = () => dialog.evaluate(node => [node.scrollTop, node.querySelector('.dialog-body').scrollTop, node.clientHeight]);
    const before = await scroll();
    await trigger.click();
    await menu.waitFor();
    const box = await menu.evaluate(async node => {
      await Promise.all(node.getAnimations().map(animation => animation.finished));
      const anchor = node.closest('dialog').querySelector('.harness-actions-trigger').getBoundingClientRect();
      const rect = node.getBoundingClientRect();
      return { topLayer: node.matches(':popover-open'), leftOffset: rect.left - anchor.left, gap: anchor.top - rect.bottom,
        inViewport: rect.left >= 0 && rect.top >= 0 && rect.right <= innerWidth && rect.bottom <= innerHeight };
    });
    assert.ok(box.topLayer && box.inViewport && Math.abs(box.leftOffset) <= 1 && box.gap >= 4 && box.gap <= 6,
      'the menu opens just above the footer trigger ' + JSON.stringify(box));
    assert.deepEqual(await scroll(), before);
    const remove = menu.getByRole('menuitem', { name: '删除配置' });
    if (await remove.count()) assert.ok(await remove.evaluate(node => getComputedStyle(node).color !== getComputedStyle(node.parentElement.firstElementChild).color));
    await capture(captureName, dialog);
    await page.keyboard.press('ArrowDown');
    assert.ok(await menu.getByRole('menuitem', { name: '恢复 Studio 编码基线' }).evaluate(node => node === document.activeElement));
    await page.keyboard.press('Escape');
    await menu.waitFor({ state: 'detached' });
    assert.ok(await trigger.evaluate(node => document.activeElement === node));
    assert.ok(await dialog.isVisible());
  }
  const checkWidth = dialog => dialog.evaluate(node => {
    const body = node.querySelector('.dialog-body');
    return node.offsetWidth >= Math.min(780, innerWidth - 50) && node.offsetWidth < innerWidth &&
      body.scrollWidth <= body.clientWidth + 1;
  });
  async function checkSectionHover(dialog, theme) {
    const composition = dialog.locator('.harness-composition');
    await composition.evaluate(node => node.scrollIntoView({ block: 'center' }));
    const disclosure = composition.locator('.harness-section-toggle').first();
    await assertSettingsRowLinkHover(page, disclosure, '.harness-section-row');
    await capture('prompt-hover-' + theme, composition);
    await disclosure.press('Tab');
    await page.keyboard.press('Shift+Tab');
    assert.ok(await disclosure.evaluate(node => {
      const label = node.querySelector('.harness-section-label');
      return node.matches(':focus-visible') && getComputedStyle(label).outlineStyle === 'solid' &&
        label.getBoundingClientRect().left - node.closest('details').getBoundingClientRect().left >= 3;
    }));
  }
  await baseline.waitFor();
  assert.equal(await cards.count(), 1);
  assert.equal(await grid.locator(':scope > *').count(), 1);
  const [policyBounds, createBounds] = await Promise.all([policyButton.boundingBox(), create.boundingBox()]);
  assert.ok(policyBounds && createBounds);
  assert.equal(createBounds.y, policyBounds.y);
  assert.equal(createBounds.height, policyBounds.height);
  assert.ok(createBounds.x > policyBounds.x + policyBounds.width);
  assert.equal(await harness.getByRole('textbox').count(), 0);
  await capture('built-in-profile');

  await create.click();
  const newProfile = harness.getByRole('dialog', { name: '新建 Harness 配置', exact: true });
  assert.ok(await checkWidth(newProfile));
  const name = newProfile.getByLabel('方案名称', { exact: true });
  const id = newProfile.getByLabel('配置 ID', { exact: true });
  await name.pressSequentially('Review');
  assert.equal(await id.inputValue(), 'review');
  await name.fill('代码审查');
  assert.match(await id.inputValue(), /^profile-[a-z0-9]{8}$/);
  await id.fill('studio-coding');
  assert.ok(await newProfile.getByRole('button', { name: '创建配置' }).isDisabled());
  await id.fill('qa-review');
  const automaticMark = await markOf(iconButton(newProfile));
  await iconButton(newProfile).click();
  assert.equal(await newProfile.getByRole('radio').count(), 10);
  await newProfile.getByText('错层', { exact: true }).click();
  await newProfile.getByTitle('藤紫', { exact: true }).click();
  await newProfile.getByRole('button', { name: '恢复自动匹配' }).click();
  assert.deepEqual(await markOf(iconButton(newProfile)), automaticMark);
  await newProfile.getByText('递进', { exact: true }).click();
  await newProfile.getByTitle('藤紫', { exact: true }).click();
  assert.ok(await newProfile.getByRole('radio', { name: '藤紫' }).isChecked());
  await capture('icon-picker-light', newProfile.locator('.settings-form-section').first());
  await iconButton(newProfile).click();
  assert.notEqual(await newProfile.locator('.harness-composition').getAttribute('open'), null);
  await checkSectionHover(newProfile, 'light');
  await newProfile.locator('.harness-section-toggle').first().press('Enter');
  const override = newProfile.getByLabel('编码身份覆盖内容', { exact: true });
  await override.fill('请先核对改动范围。');
  const toggle = newProfile.getByRole('switch', { name: '编码身份' });
  await toggle.press('Space'); assert.ok(await override.isDisabled());
  await toggle.press('Space'); assert.equal(await override.inputValue(), '请先核对改动范围。');
  await newProfile.locator('.harness-composition > summary').click();
  await newProfile.locator('.harness-guidance > summary').click();
  const addNote = newProfile.getByRole('button', { name: '添加工具说明' });
  const picker = newProfile.getByRole('combobox', { name: '工具名称' });
  const note = newProfile.getByRole('textbox', { name: '使用说明' });
  await addNote.click();
  assert.ok(await picker.evaluate(node => document.activeElement === node));
  assert.equal(await newProfile.getByRole('alert').count(), 0);
  const firstOption = await picker.getAttribute('aria-activedescendant');
  await picker.press('ArrowDown');
  assert.notEqual(await picker.getAttribute('aria-activedescendant'), firstOption);
  await picker.press('Escape');
  await page.waitForFunction(() => document.activeElement?.matches('.harness-add-guidance'));
  await addNote.click();
  await picker.fill('read');
  await picker.press('Enter');
  assert.ok(await newProfile.getByRole('button', { name: '创建配置' }).isDisabled());
  await note.fill('先核对文件路径。');
  await addNote.click();
  await picker.fill('read');
  await newProfile.getByRole('status').filter({ hasText: '已有说明' }).waitFor();
  assert.equal(await newProfile.getByRole('option', { name: 'read', exact: true }).count(), 0);
  await picker.fill('constructor');
  assert.equal(await newProfile.getByRole('option').count(), 0);
  await picker.fill('review.changes');
  await picker.press('Enter');
  await note.fill('修改后运行与改动相关的测试。');
  await newProfile.getByRole('button', { name: '更换工具 review.changes' }).click();
  await picker.fill('edit');
  await newProfile.getByRole('option', { name: 'edit', exact: true }).click();
  assert.equal(await note.inputValue(), '修改后运行与改动相关的测试。');
  await capture('guidance-edit-light', newProfile.locator('.harness-guidance'));
  await newProfile.getByRole('button', { name: '创建配置', exact: true }).click();
  await newProfile.waitFor({ state: 'detached' });
  const custom = cards.filter({ hasText: 'qa-review' });
  await custom.waitFor();
  let originalMark = await markOf(custom);
  assert.equal(originalMark.shape, 'ascending');
  assert.equal(originalMark.ink, 'berry');
  assert.notDeepEqual(originalMark.layers, (await markOf(baseline)).layers);
  assert.ok(await create.isVisible());
  let snapshot = await saved();
  assert.notEqual(snapshot.globalProfileId, 'qa-review');
  assert.notEqual(snapshot.workspaceProfileId, 'qa-review');
  assert.deepEqual(snapshot.profiles.find(row => row.id === 'qa-review').toolGuidance,
    { read: '先核对文件路径。', edit: '修改后运行与改动相关的测试。' });

  await custom.press('Enter');
  await edit.getByRole('button', { name: '应用到工作区', exact: true }).click();
  await edit.getByRole('button', { name: '已应用', exact: true }).waitFor();
  assert.equal((await saved()).workspaceProfileId, 'qa-review');
  await edit.getByRole('button', { name: '恢复继承', exact: true }).click();
  await edit.getByRole('button', { name: '应用到工作区', exact: true }).waitFor();
  assert.equal((await saved()).workspaceProfileId, '');
  await edit.locator('.harness-section-toggle').first().click();
  assert.equal(await edit.getByLabel('编码身份覆盖内容').inputValue(), '请先核对改动范围。');
  await capture('editor');
  await edit.getByLabel('方案名称').fill('发布审查');
  await iconButton(edit).click();
  await edit.getByRole('radio', { name: '藤紫' }).press('ArrowLeft');
  assert.ok(await edit.getByRole('radio', { name: '海蓝' }).isChecked());
  await iconButton(edit).click();
  await edit.getByRole('button', { name: '保存配置' }).click();
  await edit.waitFor({ state: 'detached' });
  await harness.getByRole('button', { name: '编辑发布审查', exact: true }).waitFor();
  originalMark = { ...originalMark, ink: 'ocean' };
  assert.deepEqual(await markOf(custom), originalMark);
  assert.deepEqual((await saved()).profiles.find(row => row.id === 'qa-review').icon, { shape: 'ascending', ink: 'ocean' });
  await capture('marks-light', grid);
  await nav.locator('[data-settings-page="general"]').click();
  await page.getByRole('button', { name: '深色', exact: true }).click();
  await nav.locator('[data-settings-page="harness"]').click();
  await custom.waitFor();
  assert.deepEqual(await markOf(custom), originalMark);
  await capture('marks-dark', grid);
  await capture('cards');

  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await baseline.click();
  await checkMoreMenu(edit, 'more-menu-builtin');
  await edit.getByRole('button', { name: '应用到工作区', exact: true }).click();
  await cancel(edit);
  await custom.click();
  await checkMoreMenu(edit, 'more-menu-dark');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await iconButton(edit).click();
  await capture('icon-picker-dark', edit.locator('.settings-form-section').first());
  await edit.getByText('收束', { exact: true }).click();
  await edit.getByRole('button', { name: '取消', exact: true }).click();
  await page.getByRole('alertdialog', { name: '放弃未保存的 Harness 更改？' }).getByRole('button', { name: '放弃更改' }).click();
  await edit.waitFor({ state: 'detached' });
  assert.deepEqual(await markOf(custom), originalMark);
  await custom.click();
  await checkSectionHover(edit, 'dark');
  await edit.locator('.harness-composition > summary').click();
  await edit.locator('.harness-guidance > summary').click();
  await edit.getByRole('button', { name: '编辑 edit 的工具说明' }).click();
  await capture('guidance-edit-dark', edit.locator('.harness-guidance'));
  await edit.getByRole('button', { name: '添加工具说明' }).click();
  await edit.getByRole('combobox', { name: '工具名称' }).fill('browser_');
  const options = edit.getByRole('option');
  await options.nth(2).hover();
  await edit.getByRole('combobox', { name: '工具名称' }).press('ArrowUp');
  assert.equal(await options.nth(1).getAttribute('aria-selected'), 'true');
  assert.ok(await options.nth(2).evaluate(async hovered => {
    await Promise.allSettled(hovered.getAnimations().map(animation => animation.finished));
    return getComputedStyle(hovered).backgroundColor === getComputedStyle(hovered.parentElement.firstElementChild).backgroundColor;
  }), 'keyboard navigation leaves a single highlighted option under a stationary pointer');
  await capture('guidance-picker-dark', edit.locator('.harness-guidance'));
  await edit.getByRole('combobox', { name: '工具名称' }).press('Escape');
  await edit.getByRole('button', { name: '全局默认', exact: true }).click();
  await edit.getByRole('button', { name: '设为全局默认', exact: true }).click();
  await edit.getByRole('button', { name: '已应用', exact: true }).waitFor();
  snapshot = await saved();
  assert.equal(snapshot.globalProfileId, 'qa-review');
  assert.equal(snapshot.activeProfileId, 'studio-coding');
  await cancel(edit);
  assert.match(await baseline.innerText(), /当前工作区使用/);
  assert.match(await custom.innerText(), /全局默认/);

  await policyButton.click();
  assert.ok(await policy.getByRole('switch', { name: '自动重试', exact: true }).isVisible());
  const compression = policy.locator('.harness-policy-group > summary').filter({ hasText: '上下文压缩' });
  await compression.click();
  const threshold = policy.getByLabel('自动压缩触发阈值（百分比）', { exact: true });
  const savedThreshold = snapshot.runtimePolicy.compaction.autoCompactPercent;
  await threshold.fill('40'); await compression.click();
  await policy.getByRole('button', { name: '保存策略' }).click();
  assert.ok(await threshold.isVisible());
  assert.equal((await saved()).runtimePolicy.compaction.autoCompactPercent, savedThreshold);
  await threshold.fill('75');
  await cdp.send('Emulation.setDeviceMetricsOverride', { width: 480, height: 620, deviceScaleFactor: 1, mobile: false });
  assert.ok(await checkWidth(policy));
  await policy.getByRole('button', { name: '保存策略' }).click();
  await policy.waitFor({ state: 'detached' });
  assert.equal((await saved()).runtimePolicy.compaction.autoCompactPercent, 75);
  await custom.click();
  assert.ok(await checkWidth(edit));
  await iconButton(edit).click();
  assert.ok(await checkWidth(edit));
  await capture('icon-picker-narrow', edit.locator('.harness-identity-fields'));
  await iconButton(edit).click();
  await edit.locator('.harness-guidance > summary').click();
  await edit.getByRole('button', { name: '编辑 read 的工具说明' }).click();
  await capture('guidance-narrow', edit.locator('.harness-guidance'));
  await edit.getByRole('button', { name: '更换工具 read' }).click();
  await edit.getByRole('combobox').fill('mcp__' + 'long_name_'.repeat(11));
  assert.ok(await checkWidth(edit));
  await edit.getByRole('combobox').press('Escape');
  await capture('editor-narrow');
  await checkMoreMenu(edit, 'more-menu-narrow');
  await cdp.send('Emulation.clearDeviceMetricsOverride');
  await edit.getByRole('button', { name: '更多配置操作' }).click();
  await page.getByRole('menuitem', { name: '复制为新配置' }).click();
  assert.deepEqual(await markOf(iconButton(newProfile)), originalMark);
  await newProfile.locator('.harness-guidance > summary').click();
  await newProfile.getByRole('button', { name: '编辑 read 的工具说明' }).click();
  assert.equal(await note.inputValue(), '先核对文件路径。');
  await newProfile.getByRole('button', { name: '删除 read 的工具说明' }).click();
  assert.equal(await newProfile.getByRole('button', { name: '编辑 read 的工具说明' }).count(), 0);
  await newProfile.getByRole('button', { name: '取消', exact: true }).click();
  await page.getByRole('alertdialog', { name: '放弃未保存的 Harness 更改？' }).getByRole('button', { name: '放弃更改' }).click();
  await newProfile.waitFor({ state: 'detached' });
  assert.equal((await saved()).profiles.find(row => row.id === 'qa-review').toolGuidance.read, '先核对文件路径。');
  await custom.click();
  await edit.getByRole('button', { name: '更多配置操作' }).click();
  await page.getByRole('menuitem', { name: '删除配置' }).click();
  await page.getByRole('alertdialog', { name: '删除 Harness 配置？' }).getByRole('button', { name: '删除配置' }).click();
  await edit.waitFor({ state: 'detached' });
  await custom.waitFor({ state: 'detached' });
  assert.equal(await cards.count(), 1);
  assert.equal(await grid.locator(':scope > *').count(), 1);
  assert.ok(await create.isEnabled());
  snapshot = await saved();
  assert.equal(snapshot.globalProfileId, 'studio-coding');
  assert.equal(snapshot.workspaceProfileId, 'studio-coding');
  assert.deepEqual(errors, []);
  console.log('Passed Harness cards, icon selection and persistence, anchored footer menus, prompt hover, tool guidance, profile lifecycle, scope, policy and narrow dialogs. Captures in ' + output);
} finally {
  await app?.close();
  await rm(base, { recursive: true, force: true });
}
