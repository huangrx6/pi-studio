/** Full production app: hidden workspaces cannot paint or take focus under settings. */
import { openSessionInspection } from './fixtures/open-session-inspection.mjs';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright-core';
import { serveProductionRenderer } from './fixtures/production-renderer-server.mjs';
import { installPerformanceFixture } from './fixtures/performance.mjs';
import { installPanelFilesFixture } from './fixtures/panel-files.mjs';
import { installSettingsIsolationFixture } from './fixtures/settings-isolation.mjs';

const output = new URL('../../.qa/settings-isolation/', import.meta.url);
await mkdir(output, { recursive: true });
const server = await serveProductionRenderer(fileURLToPath(new URL('../..', import.meta.url)));
const result = { checks: [], errors: [] };
let browser;
try {
  browser = await chromium.launch({ executablePath: process.env.CHROME_BIN || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' });
  const page = await browser.newPage({ viewport: { width: 1440, height: 960 }, reducedMotion: 'reduce' });
  page.setDefaultTimeout(10_000);
  page.on('pageerror', error => result.errors.push(error.message));
  await page.route('**/*', route => route.request().url().startsWith(server.origin) ? route.continue() : route.abort());
  await page.addInitScript({ content: `(${installPerformanceFixture})({sessionCount:2,turnCount:4});(${installPanelFilesFixture})();(${installSettingsIsolationFixture})();` });
  await page.goto(server.origin);
  await page.locator('.session-row').first().click();
  await page.locator('.assistant-response').first().waitFor();
  const settings = page.getByRole('region', { name: '设置', exact: true });
  const nav = page.getByRole('navigation', { name: '设置导航', exact: true });
  const rail = page.getByRole('navigation', { name: '主导航', exact: true });
  const gear = rail.getByRole('button', { name: '设置', exact: true });
  const originalRail = await rail.elementHandle();
  const footer = page.getByRole('contentinfo', { name: '状态栏', exact: true });
  const originalFooter = await footer.elementHandle();
  const workspace = page.locator('.app > .content-region');
  async function check(name, selector, keyboard = false) {
    const surface = workspace.locator(selector).first();
    await surface.waitFor();
    const handle = await surface.elementHandle();
    const gearBox = await gear.boundingBox();
    const footerBox = await footer.boundingBox();
    if (keyboard) await page.keyboard.press('ControlOrMeta+,');
    else await gear.click();
    await settings.waitFor();
    assert.equal(await originalRail.evaluate(node => node === document.querySelector('.sidebar-rail')), true);
    assert.equal(await originalFooter.evaluate(node => node === document.querySelector('.studio-statusbar')), true);
    assert.deepEqual(await footer.boundingBox(), footerBox, 'the global status bar stays in the same position');
    const canvas = await settings.getByRole('main').boundingBox();
    assert.ok(canvas.y + canvas.height <= footerBox.y, 'settings scrolls above the status bar');
    assert.equal(await rail.count(), 1);
    assert.deepEqual(await gear.boundingBox(), gearBox, 'the settings button stays in the same position');
    assert.equal(await gear.getAttribute('aria-current'), 'page');
    assert.equal(await rail.locator('[data-sidebar-section][aria-current]').count(), 0);
    const railBox = await rail.boundingBox();
    assert.equal((await nav.boundingBox()).x, railBox.x + railBox.width);
    assert.equal(await page.getByRole('listbox').count(), 0, `${name}: workspace menus close before interacting with settings`);
    assert.equal(await page.getByRole('menu').count(), 0, `${name}: workspace action menus close before interacting with settings`);
    await nav.getByRole('button', { name: '模型配置', exact: true }).click();
    await settings.getByRole('heading', { name: '模型配置', exact: true }).waitFor();
    assert.equal(await page.getByRole('listbox').count(), 0, `${name}: workspace menus close on entry`);
    assert.equal(await handle.evaluate(node => node.isConnected), true, `${name}: workspace remains mounted`);
    const leaking = await workspace.evaluate(root => [root, ...root.querySelectorAll('*')]
      .filter(node => node.checkVisibility({ checkVisibilityCSS: true, checkOpacity: true })).map(node => node.className).slice(0, 8));
    assert.deepEqual(leaking, [], `${name}: no descendants may restore visibility`);
    await handle.evaluate(node => node.querySelector('button,input,textarea,[tabindex]')?.focus());
    assert.equal(await workspace.evaluate(root => root.contains(document.activeElement)), false, `${name}: hidden controls cannot take focus`);
    for (const label of ['快捷键', '模型配置']) {
      await nav.getByRole('button', { name: label, exact: true }).click();
      assert.equal(await surface.isVisible(), false, `${name}: hidden across settings routes`);
    }
    if (name === 'subagent-graph' || name === 'file-preview') await page.screenshot({ path: fileURLToPath(new URL(`${name}-settings.png`, output)) });
    await rail.getByRole('button', { name: '对话', exact: true }).click();
    await settings.waitFor({ state: 'detached' });
    await surface.waitFor();
    assert.equal(await handle.evaluate(node => node.isConnected && node.checkVisibility()), true, `${name}: same surface restored`);
    result.checks.push(name);
    console.log(`verified: ${name}`);
    await handle.dispose();
  }
  const inspector = page.getByRole('tablist', { name: '会话检视视图' });
  await check('conversation', '.assistant-response');
  const more = rail.getByRole('button', { name: '更多', exact: true });
  const choices = rail.getByRole('group', { name: '更多栏目' });
  await gear.click();
  await more.click();
  await choices.getByRole('checkbox', { name: '固定计划到侧边栏' }).check();
  await page.keyboard.press('Escape');
  await choices.waitFor({ state: 'hidden' });
  await nav.getByRole('button', { name: '通用', exact: true }).click();
  await settings.getByRole('heading', { name: '通用', exact: true }).waitFor();
  await page.mouse.move(0, 0);
  await page.screenshot({ path: fileURLToPath(new URL('shared-navigation.png', output)), animations: 'disabled' });
  await settings.getByRole('button', { name: '深色', exact: true }).click();
  await page.waitForFunction(() => document.documentElement.dataset.theme === 'dark');
  await page.mouse.move(0, 0);
  await page.screenshot({ path: fileURLToPath(new URL('shared-navigation-dark.png', output)), animations: 'disabled' });
  const plans = rail.getByRole('button', { name: '计划', exact: true });
  await nav.getByRole('button', { name: '测试凭据', exact: true }).click();
  const nameInput = settings.getByPlaceholder('TEST_TOKEN', { exact: true });
  await nameInput.fill('QA_NAVIGATION');
  await plans.click();
  const leave = page.getByRole('alertdialog', { name: '丢弃未保存的设置更改？' });
  await leave.getByRole('button', { name: '继续编辑' }).click();
  assert.equal(await nameInput.inputValue(), 'QA_NAVIGATION');
  await plans.click();
  await leave.getByRole('button', { name: '丢弃并离开' }).click();
  await page.getByRole('navigation', { name: '计划菜单' }).waitFor();
  assert.equal(await plans.getAttribute('aria-current'), 'page');
  await gear.click();
  await nav.waitFor();
  assert.equal(await page.getByRole('button', { name: /^返回(计划|对话)$/ }).count(), 0);
  const search = nav.getByRole('searchbox');
  await search.fill('通用');
  await search.press('Escape');
  assert.equal(await search.inputValue(), '');
  await search.press('Escape');
  await page.getByRole('navigation', { name: '计划菜单' }).waitFor();
  assert.equal(await plans.getAttribute('aria-current'), 'page');
  await gear.click();
  await nav.waitFor();
  await more.click();
  await choices.getByRole('button', { name: '团队', exact: true }).click();
  await page.getByRole('navigation', { name: '团队菜单' }).waitFor();
  await gear.click();
  await rail.getByRole('button', { name: '对话', exact: true }).click();
  await workspace.locator('.assistant-response').first().waitFor();
  assert.equal(await plans.isVisible(), true);
  result.checks.push('persistent primary navigation and footer, pin, guarded navigation from settings');
  await page.locator('.session-row-shell').first().hover();
  await page.locator('.session-row-shell').first().locator('.sidebar-row-actions button').first().click();
  await check('sidebar-menu', '.assistant-response', true);
  await openSessionInspection(page);
  await inspector.getByRole('tab', { name: /^子智能体/ }).click();
  await check('subagent-list', '.agent-list');
  await page.getByRole('button', { name: '流程图视图', exact: true }).click();
  await workspace.locator('.react-flow__node').first().waitFor();
  await check('subagent-graph', '.react-flow__node');
  await page.getByRole('button', { name: '列表视图', exact: true }).click();
  await workspace.locator('.agent-list').getByRole('button').first().click();
  await check('subagent-transcript', '.agent-transcript');
  await inspector.getByRole('tab', { name: '进展', exact: true }).click();
  await page.getByRole('button', { name: '查看全部任务', exact: true }).click();
  await page.getByRole('button', { name: '筛选任务状态', exact: true }).click();
  await check('tasks', '.session-tasks-page', true);
  await inspector.getByRole('tab', { name: '轨迹', exact: true }).click();
  await check('trace', '.conversation-trace-page');
  await page.getByRole('button', { name: '关闭会话详情', exact: true }).click();
  await page.getByRole('button', { name: '打开右侧面板' }).click();
  const modes = page.getByRole('navigation', { name: '工作区视图' });
  await modes.getByRole('button', { name: 'Git', exact: true }).click();
  await check('git', '.git-workspace-page');
  await modes.getByRole('button', { name: '文件', exact: true }).click();
  await check('files', '.panel-file-browser');
  await page.locator('.file-row').filter({ hasText: 'shared.txt' }).click();
  await check('file-preview', '.session-document .file-preview-pane');
  const serviceButton = page.getByRole('button', { name: /^运行服务(?:，|$)/ });
  await serviceButton.click();
  await page.getByRole('dialog', { name: '运行服务' }).waitFor();
  await page.keyboard.press('ControlOrMeta+,');
  await settings.waitFor();
  await page.getByRole('dialog', { name: '运行服务' }).waitFor({ state: 'hidden' });
  await footer.getByRole('button', { name: '打开工具面板', exact: true }).waitFor();
  await serviceButton.click();
  const services = page.getByRole('dialog', { name: '运行服务' });
  await services.getByRole('button', { name: /^本机全部/ }).click();
  await page.keyboard.press('Escape');
  await services.waitFor({ state: 'hidden' });
  assert.equal(await settings.isVisible(), true, 'Escape dismisses the status popover inside settings');
  await page.keyboard.press('Escape');
  await settings.waitFor({ state: 'detached' });
  await serviceButton.waitFor();
  assert.equal(await serviceButton.getAttribute('aria-expanded'), 'false');
  result.checks.push('services');
  assert.deepEqual(result.errors, []);
  console.log(JSON.stringify(result));
} finally {
  await writeFile(new URL('results.json', output), JSON.stringify(result, null, 2));
  await browser?.close();
  await server.close();
}
