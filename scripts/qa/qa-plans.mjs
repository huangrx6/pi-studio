/** Real Electron, a disposable Studio profile and a model served only on loopback. */
import assert from 'node:assert/strict';
import { mkdir, mkdtemp, rm } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { launchTestDesktop, configureTestModel } from './fixtures/isolated-desktop.mjs';
import { startChecklistModel } from './fixtures/checklist-model.mjs';

const output = fileURLToPath(new URL('../../.qa/screenshots/plans/', import.meta.url));
await mkdir(output, { recursive: true });
const profile = await mkdtemp(path.join(output, 'profile-'));
const workspace = path.join(profile, '研发工作台');
await mkdir(workspace);
const model = await startChecklistModel();
let app;
try {
  const desktop = await launchTestDesktop(workspace, profile, 1240, 820);
  app = desktop.app;
  const { page } = desktop;
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.evaluate(() => window.piApi.waitForStartup());
  await configureTestModel(page, workspace, model.baseUrl);
  const rail = page.getByRole('navigation', { name: '主导航' });
  const button = (name, inside = page) => inside.getByRole('button', { name, exact: true });
  const more = button('更多', rail);
  const pin = rail.getByRole('checkbox', { name: '固定计划到侧边栏' });
  const openHidden = async () => { await more.click(); await button('计划', rail).click(); };
  const editor = page.getByRole('dialog');
  const title = '工作日项目简报';
  const actions = async label => {
    await button(title + '的操作').click();
    await page.getByRole('menuitem', { name: label, exact: true }).click();
  };
  async function checkMoreRows(theme) {
    await more.click();
    const hovered = button('插件', rail.locator('.sidebar-more'));
    const current = rail.locator('.sidebar-more [aria-current="page"]');
    await hovered.hover();
    const [above, below] = await Promise.all([hovered.boundingBox(), current.boundingBox()]);
    assert.equal(below.y - above.y - above.height, 8);
    assert.notEqual(await hovered.evaluate(el => getComputedStyle(el).backgroundColor), await current.evaluate(el => getComputedStyle(el).backgroundColor));
    await page.locator('.sidebar-more').screenshot({ path: path.join(output, 'more-' + theme + '.png') });
    await page.keyboard.press('Escape');
  }
  await more.waitFor();
  assert.deepEqual(await rail.locator('.sidebar-rail-sections > button').evaluateAll(nodes => nodes.map(n => n.getAttribute('aria-label'))), ['对话', '临时对话', '更多']);
  assert.equal(await page.locator('.sidebar-secondary h2').count(), 0);
  await more.focus();
  await more.press('Enter');
  await pin.waitFor();
  assert.equal(await pin.isChecked(), false);
  await page.keyboard.press('Escape');
  await pin.waitFor({ state: 'hidden' });
  await openHidden();
  await page.getByRole('heading', { name: '执行日程' }).waitFor();
  assert.equal(await rail.locator('[data-sidebar-section="plans"]').count(), 0);
  await more.click();
  await pin.check();
  await page.keyboard.press('Escape');
  await page.reload();
  await button('计划', rail).click();
  await more.click();
  await pin.uncheck();
  await page.keyboard.press('Escape');
  await page.getByRole('heading', { name: '执行日程' }).waitFor();
  assert.equal(await rail.locator('[data-sidebar-section="plans"]').count(), 0);
  await page.evaluate(() => { document.documentElement.dataset.theme = 'dark'; });
  const calendar = page.getByRole('region', { name: '周日程' });
  const create = button('新建计划', page.locator('.plans-heading'));
  async function checkCreatePlacement() {
    assert.equal(await button('新建计划').count(), 1);
    const [heading, action] = await Promise.all([page.getByRole('heading', { name: '执行日程' }).boundingBox(), create.boundingBox()]);
    assert.ok(action.x >= heading.x + heading.width);
    assert.ok(Math.abs(heading.y + heading.height / 2 - action.y - action.height / 2) <= 1);
  }
  const dates = calendar.getByRole('group', { name: '选择日期' }).getByRole('button');
  const selectedDay = calendar.locator('[aria-pressed="true"]');
  const today = await calendar.locator('[aria-current="date"]').getAttribute('data-date');
  assert.equal(await dates.count(), 7);
  assert.equal(await selectedDay.getAttribute('data-date'), today);
  assert.equal(await page.locator('.shell-header .main-app-title').count(), 0);
  assert.ok(await page.getByRole('button', { name: /^运行服务(?:，|$)/ }).getByText('相关服务').isVisible());
  await checkCreatePlacement();
  await create.press('Enter');
  await editor.getByText('每天', { exact: true }).waitFor();
  await page.keyboard.press('Escape');
  await editor.waitFor({ state: 'hidden' });
  assert.ok(await create.evaluate(el => el === document.activeElement));
  await button('上一周', calendar).click();
  await page.getByText('当天没有执行记录', { exact: true }).waitFor();
  assert.ok(await create.isVisible());
  await button('今天', calendar).click();
  await button('下一周', calendar).click();
  assert.notEqual(await selectedDay.getAttribute('data-date'), today);
  const nextWeekDay = await selectedDay.getAttribute('data-date');
  await create.click();
  await editor.getByText('仅一次', { exact: true }).waitFor();
  assert.equal((await editor.getByRole('button', { name: /^执行日期/ }).innerText()).replaceAll('/', '-').trim(), nextWeekDay);
  await button('取消', editor).click();
  await button('今天', calendar).click();
  await page.getByText('今天还没有安排', { exact: true }).waitFor();
  assert.deepEqual(await page.locator('.plan-hour-ruler > span').allTextContents(), ['00:00', '08:00', '16:00', '24:00']);
  assert.equal(await page.locator('.plan-day-empty').getByRole('button').count(), 0);
  assert.equal(await page.locator('.plan-upcoming-empty [aria-hidden]').innerText(), '—');
  await selectedDay.focus();
  await selectedDay.press('Home');
  assert.equal(await dates.first().getAttribute('aria-pressed'), 'true');
  await selectedDay.press('ArrowLeft');
  await page.waitForFunction(() => document.activeElement?.matches('.plan-date-strip button:last-child[aria-pressed="true"]'));
  await button('今天', calendar).click();
  const row = page.getByRole('button', { name: /使用模板 工作日项目简报/ });
  await row.getByText('汇总上个工作日以来的进展和待办。').waitFor();
  assert.ok((await row.boundingBox()).height <= 96);
  await row.hover();
  assert.equal(await row.locator('.plan-template-use').evaluate(el => getComputedStyle(el).opacity), '1');
  await page.mouse.move(0, 0);
  await page.screenshot({ path: path.join(output, 'empty-dark.png') });
  await checkMoreRows('dark');
  const release = '每周发布摘要';
  await page.getByRole('button', { name: /使用模板 每周发布摘要/ }).click();
  assert.equal(await editor.getByLabel('计划名称').inputValue(), release);
  assert.equal(await editor.getByLabel('执行时间').inputValue(), '17:00');
  assert.equal(await button('星期五', editor).getAttribute('aria-pressed'), 'true');
  const releasePrompt = await editor.getByLabel('执行指令').inputValue();
  assert.match(releasePrompt, /发布前确认/);
  assert.match(releasePrompt, /最近七天/);
  await button('取消', editor).click();
  const browse = button('浏览模板');
  const library = page.getByRole('dialog', { name: '浏览计划模板' });
  await browse.click();
  const briefChoice = library.getByRole('radio', { name: title });
  const releaseChoice = library.getByRole('radio', { name: release });
  assert.ok(await briefChoice.isChecked());
  await briefChoice.press('ArrowRight');
  assert.ok(await releaseChoice.isChecked());
  await library.getByText('每周五 · 17:00').waitFor();
  await library.getByText(/当前分支最近七天/).waitFor();
  await library.getByText('发布前确认', { exact: true }).waitFor();
  assert.ok(await library.evaluate(el =>
    getComputedStyle(el.querySelector('.dialog-footer-hint')).color === getComputedStyle(el.querySelector('dt')).color));
  await releaseChoice.press('Escape');
  await library.waitFor({ state: 'hidden' });
  assert.ok(await browse.evaluate(el => el === document.activeElement));
  assert.deepEqual(await page.evaluate(() => window.piApi.planList()), []);
  await browse.press('Enter');
  await library.getByText(release, { exact: true }).click();
  await page.mouse.move(0, 0);
  await page.screenshot({ path: path.join(output, 'template-preview-dark.png') });
  await button('使用模板', library).click();
  assert.equal(await editor.getByLabel('执行指令').inputValue(), releasePrompt);
  await button('取消', editor).click();
  await browse.click();
  await button('使用模板', library).click();
  assert.equal(await editor.getByLabel('计划名称').inputValue(), title);
  assert.match(await editor.getByLabel('执行指令').inputValue(), /今天跟进/);
  assert.equal(await editor.getByLabel('执行时间').inputValue(), '09:00');
  // Let the actual open-folder IPC adopt this temporary project.
  await app.evaluate(({ dialog }, cwd) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [cwd] }); }, workspace);
  await button('打开项目文件夹', editor).click();
  await editor.getByText('研发工作台', { exact: true }).waitFor();
  await editor.getByText(/下次执行/).waitFor();
  const aligned = await editor.locator('.plan-form-pair').evaluateAll(pairs => pairs.every(pair => {
    const controls = [...pair.children].map(field => field.querySelector('input, .pi-select-trigger').getBoundingClientRect());
    return Math.abs(controls[0].top - controls[1].top) <= 1;
  }));
  assert.ok(aligned, 'the name/project and cadence/time controls each share a baseline');
  await page.screenshot({ path: path.join(output, 'editor-dark.png') });
  await editor.getByLabel('执行指令').fill('QA-DONE 汇总当前项目的变化。');
  await button('创建计划', editor).click();
  await editor.waitFor({ state: 'hidden' });
  await button('今天', calendar).click();
  await button('下一周', calendar).click();
  await calendar.locator('.mark-active').first().waitFor();
  assert.deepEqual(await dates.evaluateAll(nodes => nodes.map(el => !!el.querySelector('.mark-active'))), [true, true, true, true, true, false, false]);
  await dates.nth(4).click();
  await page.locator('.plan-day-item').getByText(title, { exact: true }).waitFor();
  await calendar.locator('.plan-upcoming button').click();
  assert.equal(await selectedDay.getAttribute('data-date'), await page.evaluate(async () => {
    const plan = (await window.piApi.planList())[0];
    return new Date(plan.nextAt).toLocaleDateString('sv-SE');
  }));
  await page.screenshot({ path: path.join(output, 'agenda-dark.png') });
  await actions('暂停计划');
  await page.getByText('已暂停', { exact: true }).waitFor();
  assert.equal(await calendar.locator('.mark-active').count(), 0);
  await actions('恢复计划');
  await page.getByText('已暂停', { exact: true }).waitFor({ state: 'hidden' });
  await button('立即运行 ' + title).click();
  await model.reply('QA-DONE', 'finish');
  await actions('查看运行记录');
  const log = page.locator('.plan-log-entry').first();
  await log.getByText('已完成', { exact: true }).waitFor();
  await log.locator('summary').click();
  await log.getByText('已结束本次验收。', { exact: true }).waitFor();
  await page.screenshot({ path: path.join(output, 'history-dark.png') });
  await button('查看完整会话', log).click();
  await page.getByText('已结束本次验收。', { exact: true }).waitFor();
  await openHidden();
  await button('计划列表').click();
  await actions('编辑计划');
  await button('执行频率', editor).click();
  await page.getByRole('option', { name: '固定间隔' }).click();
  await editor.getByLabel('间隔分钟数').fill('1');
  await editor.getByLabel('执行指令').fill('QA-STOP 检查当前项目的进展。');
  await button('保存更改', editor).click();
  await editor.waitFor({ state: 'hidden' });
  await page.locator('.plan-agenda-name').getByText(/每隔 1 分钟/).waitFor();
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(840, 680));
  await page.evaluate(() => { document.documentElement.dataset.theme = 'light'; });
  const fits = await page.locator('.plans-canvas').evaluate(el => el.scrollWidth <= el.clientWidth);
  assert.ok(fits);
  await button('今天', calendar).click();
  await page.locator('.plans-canvas').evaluate(el => { el.scrollTop = 0; });
  await checkCreatePlacement();
  await page.screenshot({ path: path.join(output, 'agenda-light.png') });
  await browse.click();
  await library.getByText('项目进展', { exact: true }).waitFor();
  assert.ok(await library.evaluate(el => el.scrollWidth <= el.clientWidth));
  await page.screenshot({ path: path.join(output, 'template-preview-light.png') });
  await button('取消', library).click();
  await checkMoreRows('light');
  const rowMenu = button(title + '的操作');
  await rowMenu.click();
  const edit = page.getByRole('menuitem', { name: '编辑计划' });
  await edit.waitFor();
  // The focus-induced scroll can arrive after the menu has already measured its anchor.
  await page.locator('.plans-canvas').evaluate(el => el.dispatchEvent(new Event('scroll')));
  assert.ok(await edit.isVisible());
  await page.locator('.plans-canvas').evaluate(el => { el.scrollTop = 0; });
  await edit.waitFor({ state: 'hidden' });

  // Wait for the real one-minute alarm with the user looking at another section.
  await button('对话', rail).click();
  await page.evaluate(() => new Promise((resolve, reject) => {
    const check = async () => {
      const { items } = await window.piApi.planHistory();
      if (items.some(r => r.trigger === 'scheduled')) { unsubscribe(); clearTimeout(timer); resolve(); }
    };
    const unsubscribe = window.piApi.onPlansChanged(check);
    const timer = setTimeout(() => { unsubscribe(); reject(Error('定时运行未触发')); }, 85_000);
    void check();
  }));
  await model.wait('QA-STOP');
  await openHidden();
  await button('停止 ' + title).click();
  await actions('暂停计划');
  await page.locator('.plan-agenda').getByText('已暂停', { exact: true }).waitFor();
  await actions('查看运行记录');
  await log.getByText('已停止', { exact: true }).waitFor();
  const history = await page.evaluate(() => window.piApi.planHistory());
  assert.deepEqual(history.items.map(r => [r.trigger, r.status]), [['scheduled', 'cancelled'], ['manual', 'succeeded']]);
  await button('计划列表').click();
  await actions('删除计划');
  await button('删除计划', page.getByRole('alertdialog', { name: '删除计划' })).click();
  await page.locator('.plan-agenda').waitFor({ state: 'hidden' });
  assert.equal((await page.evaluate(() => window.piApi.planHistory())).items.length, 2);
  await button('新建计划').click();
  await editor.getByLabel('计划名称').fill('月末归档');
  await editor.getByLabel('执行指令').fill('整理本月项目变化。');
  await button('执行频率', editor).click();
  await page.getByRole('option', { name: '每月', exact: true }).click();
  await button('每月执行日', editor).click();
  await page.getByRole('option', { name: '最后一天', exact: true }).click();
  await editor.getByText(/下次执行/).waitFor();
  await button('创建计划', editor).click();
  await page.locator('.plan-agenda-name').getByText(/每月最后一天/).waitFor();
  assert.deepEqual(errors, []);
  console.log('Verified the week and day timelines, template previews, editable drafts, keyboard navigation, dialog alignment, menu spacing, theme layouts, a real timer and run history. Screenshots in ' + output);
} finally {
  try { await app?.close(); } finally { await model.close(); await rm(profile, { recursive: true, force: true }); }
}
